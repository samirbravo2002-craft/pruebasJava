package Metodos;



   //metodo uno: sin parametros y sin retorno
public class metodoUno { //clase principal

         /*despues de "mostrarMensaje" dentro de los parentesis (PARAMETRO) va el 
         parametro, parametro que no esta definido, por eso es sin parametros */



         /* es sin retorno, ya que la palabra "void" indica que no devuelve ningún 
         valor, osea solo ejecuta una accion, de lo contrario podria guardar datos
         con un return*/
    public static void mostrarMensaje() { //metodo
        System.out.println("hola mundo");
    }

    public static void main(String[] args) {
        mostrarMensaje();
    }



    
}
